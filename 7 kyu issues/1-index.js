function switcher(arr) {
    let cur = ""
    for (let val of arr) {
        cur += (val === "26") ? "a" :
            (val === "25") ? "b" :
                (val === "24") ? "c" :
                    (val === "23") ? "d" :
                        (val === "22") ? "e" :
                            (val === "21") ? "f" :
                                (val === "20") ? "g" :
                                    (val === "19") ? "h" :
                                        (val === "18") ? "i" :
                                            (val === "17") ? "j" :
                                                (val === "16") ? "k" :
                                                    (val === "15") ? "l" :
                                                        (val === "14") ? "m" :
                                                            (val === "13") ? "n" :
                                                                (val === "12") ? "o" :
                                                                    (val === "11") ? "p" :
                                                                        (val === "10") ? "q" :
                                                                            (val === "9") ? "r" :
                                                                                (val === "8") ? "s" :
                                                                                    (val === "7") ? "t" :
                                                                                        (val === "6") ? "u" :
                                                                                            (val === "5") ? "v" :
                                                                                                (val === "4") ? "w" :
                                                                                                    (val === "3") ? "x" :
                                                                                                        (val === "2") ? "y" :
                                                                                                            (val === "1") ? "z" :
                                                                                                                (val === "27") ? "!" :
                                                                                                                    (val === "28") ? "?" :
                                                                                                                        (val === "29") ? " " : ""
    }
    return cur
}


switcher(["24", "12", "23", "22", "4", "26", "9", "8", "28", "29", "27"])